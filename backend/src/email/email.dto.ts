import {
  ArrayMinSize, Equals, IsArray, IsBoolean, IsIn, IsObject, IsOptional, IsString, IsUUID, Length, MaxLength,
} from 'class-validator';
import { TEMPLATE_KINDS, TemplateKind } from '../database/entities';

export class TemplateDto {
  @IsString() @Length(1, 160) name: string;
  @IsIn(TEMPLATE_KINDS as unknown as string[]) kind: TemplateKind;
  @IsOptional() @IsUUID() vacancyId?: string | null;
  @IsString() @Length(1, 300) subject: string;
  @IsString() @Length(1, 20000) body: string;
  @IsOptional() @IsBoolean() active?: boolean;
}

export class ComposeDto {
  @IsArray() @ArrayMinSize(1) @IsUUID('all', { each: true }) applicationIds: string[];
  @IsIn(TEMPLATE_KINDS as unknown as string[]) kind: TemplateKind;
  @IsOptional() @IsUUID() templateId?: string;
  @IsString() @Length(1, 300) subject: string;
  @IsString() @Length(1, 20000) body: string;
  @IsOptional() @IsObject() variables?: Record<string, string>;
}

export class SendDto extends ComposeDto {
  /** Generated by the client per send attempt; resubmitting the same key cannot send twice. */
  @IsString() @Length(8, 80) clientKey: string;
  /** Bulk sending requires explicit confirmation after preview (SRS 12.4). */
  @IsBoolean() @Equals(true, { message: 'Confirm the preview before sending.' }) confirmed: boolean;
}

export class HistoryQuery {
  @IsOptional() @IsUUID() vacancyId?: string;
  @IsOptional() @IsIn(['Queued', 'Sent', 'Failed']) status?: string;
  @IsOptional() @IsString() @MaxLength(30) kind?: string;
}
